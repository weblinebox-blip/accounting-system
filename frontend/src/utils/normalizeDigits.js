// تبدیل ارقام فارسی و عربی به ارقام انگلیسی (لاتین)
// برای اطمینان از اینکه مقادیر عددی همیشه با فرمت استاندارد ذخیره/محاسبه می‌شوند،
// صرف‌نظر از تنظیمات زبان سیستم یا نحوه‌ی تایپ کاربر.
const DIGIT_MAP = {
  '۰': '0', '۱': '1', '۲': '2', '۳': '3', '۴': '4', '۵': '5', '۶': '6', '۷': '7', '۸': '8', '۹': '9', // فارسی
  '٠': '0', '١': '1', '٢': '2', '٣': '3', '٤': '4', '٥': '5', '٦': '6', '٧': '7', '٨': '8', '٩': '9', // عربی
};

export function toEnglishDigits(value) {
  if (value === null || value === undefined) return value;
  return String(value).replace(/[۰-۹٠-٩]/g, (ch) => DIGIT_MAP[ch] ?? ch);
}
